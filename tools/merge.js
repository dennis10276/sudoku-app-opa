// node tools/merge.js out.js part1.json part2.json ...
const fs = require('fs');
const all = {};
for (const f of process.argv.slice(3)) for (const [k, v] of Object.entries(JSON.parse(fs.readFileSync(f, 'utf8')))) (all[k] = all[k] || []).push(...v);
const out = '/* Generated by tools/generate.js. Each level is a string of 81-character puzzles (0 = empty). */\nconst PUZZLES = {\n' +
  Object.entries(all).map(([k, v]) => `  ${k}: '${[...new Set(v)].join('')}'`).join(',\n') + '\n};\n';
fs.writeFileSync(process.argv[2], out);
console.log(Object.entries(all).map(([k, v]) => k + ':' + new Set(v).size).join(' '));
