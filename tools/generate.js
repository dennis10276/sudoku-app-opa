// Generates the rated puzzle bank: node tools/generate.js <outfile> [perLevel]
const { solve, rate } = require('../core.js');
const N = +process.argv[3] || 200;
let seed = +process.env.SEED || Date.now();
function rnd() { seed = (seed * 1664525 + 1013904223) >>> 0; return seed / 4294967296; }
function shuffle(a) { for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rnd() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; }
function fullGrid() { return solve(new Array(81).fill(0), 1, rnd).solution; }
const unique = g => solve(g, 2).count === 1;
// remove symmetric pairs until clue count <= target (or minimal)
function carve(sol, target) {
  const g = sol.slice();
  let clues = 81;
  const order = shuffle([...Array(41).keys()]);
  for (const i of order) {
    if (clues <= target) break;
    const j = 80 - i;
    const a = g[i], b = g[j];
    g[i] = 0; g[j] = 0;
    if (unique(g)) clues -= (i === j ? 1 : 2);
    else { g[i] = a; g[j] = b; }
  }
  return { g, clues };
}
const want = { easy: [], medium: [], hard: [], expert: [], master: [], extreme: [] };
const full = k => want[k].length >= N;
const t0 = Date.now(); let made = 0;
while (Object.keys(want).some(k => !full(k))) {
  const sol = fullGrid(); made++;
  if (!full('easy')) {
    const { g, clues } = carve(sol, 36 + Math.floor(rnd() * 4));
    const r = rate(g);
    if (r.level === 1 && clues >= 36) want.easy.push(g.join(''));
  }
  if (!full('medium')) {
    const { g, clues } = carve(sol, 30 + Math.floor(rnd() * 3));
    const r = rate(g);
    if (r.level === 1 && clues <= 32 && clues >= 30 && r.hidden >= 10) want.medium.push(g.join(''));
  }
  if (['hard', 'expert', 'master', 'extreme'].some(k => !full(k))) {
    const { g, clues } = carve(sol, 0);
    const r = rate(g);
    let key = { 2: 'hard', 3: 'expert', 4: 'expert', 5: 'master', 6: 'extreme' }[r.level];
    if (r.level === 5 && (r.chains >= 3 || r.chainMax > 2)) key = 'extreme';
    if (key && !full(key)) want[key].push(g.join(''));
  }
  if (made % 500 === 0) console.error(made, ((Date.now() - t0) / 1000).toFixed(0) + 's', Object.entries(want).map(([k, v]) => k + ':' + v.length).join(' '));
}
if (process.argv[2].endsWith('.json')) { require('fs').writeFileSync(process.argv[2], JSON.stringify(want)); console.error('done', made); process.exit(0); }
const out = '/* Generated by tools/generate.js. Each level is a string of 81-character puzzles (0 = empty). */\nconst PUZZLES = {\n' +
  Object.entries(want).map(([k, v]) => `  ${k}: '${v.join('')}'`).join(',\n') + '\n};\n';
require('fs').writeFileSync(process.argv[2], out);
console.error('done', made, 'grids');
